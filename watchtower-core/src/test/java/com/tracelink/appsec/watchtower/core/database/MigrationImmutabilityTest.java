package com.tracelink.appsec.watchtower.core.database;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.zip.CRC32;

import org.junit.jupiter.api.Test;

public class MigrationImmutabilityTest {

	@Test
	public void testDeployedMetricsMigrationChecksumsRemainImmutable() throws IOException {
		assertEquals(-1553298366, checksum("V039__Create_Metrics_Projections.sql"));
		assertEquals(-2103833108, checksum("V040__Backfill_Metrics_Projections.sql"));
	}

	@Test
	public void testIdempotencyChangesUseForwardMigrations() throws IOException {
		String schemaMigration = readMigration("V042__Create_Metrics_Processed_Scan.sql");
		String dataMigration = readMigration("V043__Backfill_Metrics_Processed_Scan.sql");

		assertTrue(schemaMigration.contains("CREATE TABLE metrics_processed_scan"));
		assertTrue(dataMigration.contains("INSERT INTO metrics_processed_scan"));
	}

	@Test
	public void testScanWorkItemIdentityUsesProductionMySqlSyntax() throws IOException {
		String migration = readMigration("V047__Create_PR_Scan_Work_Items.sql");

		assertTrue(migration.contains("AUTO_INCREMENT"));
		assertTrue(!migration.contains("GENERATED BY DEFAULT AS IDENTITY"));
		assertTrue(migration.contains("dedup_key VARCHAR(64) NOT NULL UNIQUE"));
	}

	private int checksum(String migration) throws IOException {
		CRC32 crc32 = new CRC32();
		try (BufferedReader reader = new BufferedReader(new InputStreamReader(
				migrationStream(migration), StandardCharsets.UTF_8))) {
			String line;
			while ((line = reader.readLine()) != null) {
				crc32.update(line.getBytes(StandardCharsets.UTF_8));
			}
		}
		return (int) crc32.getValue();
	}

	private String readMigration(String migration) throws IOException {
		try (InputStream stream = migrationStream(migration)) {
			return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
		}
	}

	private InputStream migrationStream(String migration) {
		InputStream stream = getClass().getClassLoader()
				.getResourceAsStream("db/migration/" + migration);
		assertNotNull(stream, "Missing migration " + migration);
		return stream;
	}
}

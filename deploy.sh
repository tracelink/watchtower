#!/usr/bin/env bash
#
# Watchtower build + deploy script.
#
# Usage:
#   ./deploy.sh dev [--dry-run] [--yes]
#   ./deploy.sh prod [--dry-run] [--yes]
#
#   --dry-run   print every command instead of running docker/kubectl actions
#   --yes / -y  skip the interactive confirmation prompt (prod only)
#
# Idempotent: safe to re-run after a partial failure. Steps 1, 2, and the
# docker build in step 5 check whether the work is already done (valid SSO
# session, kubectl already on the right context, image tag already built
# locally) and skip it rather than redoing it.
#
# What it does, in order:
#   1. AWS SSO login for the target environment (skipped if already logged in)
#   2. Point kubectl at the target EKS cluster (skipped if already there)
#   3. Reuse the cluster-managed watchtower-secrets Secret when it exists.
#      It is validated but never downloaded for local use or reapplied. On a
#      first deploy only, legacy ConfigMap database values can be migrated and
#      the bootstrap password supplied through the environment.
#   4. Log docker in to the target ECR registry
#   5. Look up the highest existing 26.1.N tag in ECR and build the next one
#   6. docker build (skipped if that tag is already built locally) / tag / push
#   7. Render deploy.yaml into a scratch copy (the checked-in file is never
#      modified — it stays a valid, human-readable reference with real
#      default values). The new image always goes in. Everything else that
#      could have been hand-tuned live — replicas, CPU/memory requests and
#      limits, SPRING_PROFILES_ACTIVE, the watchtower.* feature-flag and
#      thread-count env vars, and the ALB group.name/tags annotations — is
#      overridden with whatever is already live on the target cluster *if*
#      a live deployment/ingress exists there, so a redeploy never silently
#      reverts tuning someone did by hand; otherwise deploy.yaml's own
#      default is used as-is (a first deploy to a new cluster just starts
#      from the file). certificate-arn and security-groups are the
#      exception: deploy.yaml only has placeholder text for those (no real
#      default), so they must come from a live ingress or the script stops
#      with an error rather than apply garbage.
#      Requires python3 with PyYAML (pip install pyyaml) to do this
#      precisely — see render step below.
#   8. kubectl apply the rendered manifest
#
set -euo pipefail

# ---------------------------------------------------------------------------
# Per-environment configuration
# ---------------------------------------------------------------------------
DEV_ECR_REGISTRY="111122223333.dkr.ecr.us-east-1.amazonaws.com"
PROD_ECR_REGISTRY="444455556666.dkr.ecr.us-east-1.amazonaws.com"

DEV_INGRESS_HOST="dev-watchtower.example.net"
PROD_INGRESS_HOST="watchtower.example.net"

AWS_REGION="us-east-1"
IMAGE_REPO="watchtower"
NAMESPACE="watchtower"
DEPLOY_FILE="deploy.yaml"
SECRET_NAME="watchtower-secrets"
VERSION_PREFIX="26.1"

# ---------------------------------------------------------------------------
# Args
# ---------------------------------------------------------------------------
ENVIRONMENT="${1:-}"
DRY_RUN=false
AUTO_YES=false
for arg in "${@:2}"; do
  case "$arg" in
    --dry-run) DRY_RUN=true ;;
    --yes|-y) AUTO_YES=true ;;
    *) echo "Unknown argument: $arg" >&2; exit 1 ;;
  esac
done

if [[ "$ENVIRONMENT" != "dev" && "$ENVIRONMENT" != "prod" ]]; then
  echo "Usage: $0 <dev|prod> [--dry-run] [--yes]" >&2
  exit 1
fi

if ! python3 -c "import yaml" >/dev/null 2>&1; then
  echo "ERROR: python3 with PyYAML is required to render deploy.yaml (pip install pyyaml)." >&2
  exit 1
fi

# Only guards the two steps that actually touch shared state (pushing to the
# registry, applying to the cluster). Everything else (auth, local build,
# read-only lookups) runs for real even under --dry-run, since none of it has
# a remote side effect and skipping it would make the lookups below fail
# without a pre-existing session.
run_if_not_dry() {
  if [[ "$DRY_RUN" == true ]]; then
    echo "    [dry-run] $*"
  else
    "$@"
  fi
}

if [[ "$ENVIRONMENT" == "dev" ]]; then
  AWS_PROFILE="dev-aws-profile"
  EKS_CLUSTER="dev-eks-cluster"
  ECR_REGISTRY="$DEV_ECR_REGISTRY"
  INGRESS_HOST="$DEV_INGRESS_HOST"
else
  AWS_PROFILE="prod-aws-profile"
  EKS_CLUSTER="prod-eks-cluster"
  ECR_REGISTRY="$PROD_ECR_REGISTRY"
  INGRESS_HOST="$PROD_INGRESS_HOST"
fi

# Generated by provision-aws.sh --aws-security-only. Validate before building or pushing.
DEPLOY_SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
AWS_SECURITY_CONFIG_FILE="${WATCHTOWER_AWS_SECURITY_CONFIG_FILE:-$DEPLOY_SCRIPT_DIR/.aws-security/$ENVIRONMENT.json}"
DEPLOY_ACCOUNT_ID="${ECR_REGISTRY%%.*}"
python3 -B - "$DEPLOY_SCRIPT_DIR/scripts" "$AWS_SECURITY_CONFIG_FILE" "$ENVIRONMENT" "$DEPLOY_ACCOUNT_ID" "$AWS_REGION" <<'PYEOF'
import sys
sys.path.insert(0, sys.argv[1])
from aws_security_deploy_config import load_settings
artifact = load_settings(*sys.argv[2:])
print("==> Security Agent: using validated provisioning output; activation is controlled by deploy.yaml"
      if artifact else "==> Security Agent: no provisioning output; deploying with the integration off")
PYEOF

echo "==> Environment:  $ENVIRONMENT"
echo "==> AWS profile:  $AWS_PROFILE"
echo "==> EKS cluster:  $EKS_CLUSTER"
echo "==> ECR registry: $ECR_REGISTRY"
echo "==> Namespace:    $NAMESPACE"
echo "==> Ingress host: $INGRESS_HOST"
[[ "$DRY_RUN" == true ]] && echo "==> DRY RUN — no docker/kubectl actions will actually execute"

if [[ "$ENVIRONMENT" == "prod" && "$AUTO_YES" != true ]]; then
  read -r -p "You are about to build and deploy to PRODUCTION. Type 'yes' to continue: " CONFIRM
  if [[ "$CONFIRM" != "yes" ]]; then
    echo "Aborted."
    exit 1
  fi
fi

# ---------------------------------------------------------------------------
# 1. AWS SSO login (skip if the session is already valid)
# ---------------------------------------------------------------------------
if aws sts get-caller-identity --profile "$AWS_PROFILE" >/dev/null 2>&1; then
  echo "==> Already logged into AWS SSO ($AWS_PROFILE), skipping login"
else
  echo "==> Logging into AWS SSO ($AWS_PROFILE)..."
  aws sso login --profile "$AWS_PROFILE"
fi

# ---------------------------------------------------------------------------
# 2. Point kubectl at the target cluster (skip if it's already pointed there)
# ---------------------------------------------------------------------------
CURRENT_CONTEXT=$(kubectl config current-context 2>/dev/null || true)
if [[ "$CURRENT_CONTEXT" == *"cluster/${EKS_CLUSTER}" ]]; then
  echo "==> kubectl already pointed at $EKS_CLUSTER, skipping kubeconfig update"
else
  echo "==> Updating kubeconfig for $EKS_CLUSTER..."
  aws eks update-kubeconfig --name "$EKS_CLUSTER" --profile "$AWS_PROFILE" --region "$AWS_REGION"
fi

# ---------------------------------------------------------------------------
# 3. Validate/reuse the live Secret expected by deploy.yaml. An existing Secret
#    is cluster-managed state: validate it in memory, then leave it untouched.
#    Only a missing Secret may be bootstrapped from the legacy ConfigMap.
# ---------------------------------------------------------------------------
echo "==> Validating Kubernetes Secret ($SECRET_NAME)..."
SECRET_WORK_DIR=$(mktemp -d)
trap 'rm -rf "$SECRET_WORK_DIR"' EXIT
LEGACY_CONFIGMAP_FILE="$SECRET_WORK_DIR/legacy-configmap.json"
CANDIDATE_SECRET_FILE="$SECRET_WORK_DIR/candidate-secret.json"

SECRET_STATUS=$(kubectl get secret "$SECRET_NAME" -n "$NAMESPACE" \
  -o go-template='{{if and (index .data "db_url") (index .data "db_user") (index .data "db_pass") (index .data "bootstrap_admin_password")}}complete{{else}}incomplete{{end}}' \
  2>/dev/null) || SECRET_STATUS="missing"

if [[ "$SECRET_STATUS" == "complete" ]]; then
  echo "    Reusing existing Kubernetes Secret; deploy.sh will not apply or modify it"
elif [[ "$SECRET_STATUS" == "incomplete" ]]; then
  echo "ERROR: existing Kubernetes Secret is incomplete; deploy.sh will not modify it." >&2
  echo "       Ensure db_url, db_user, db_pass, and bootstrap_admin_password are all non-empty in the cluster." >&2
  exit 1
else
  if ! kubectl get configmap "$SECRET_NAME" -n "$NAMESPACE" -o json \
      >"$LEGACY_CONFIGMAP_FILE" 2>/dev/null; then
    echo "ERROR: Kubernetes Secret '$SECRET_NAME' does not exist, and no legacy ConfigMap is available for first-deploy migration." >&2
    exit 1
  fi
  python3 - "$LEGACY_CONFIGMAP_FILE" "$CANDIDATE_SECRET_FILE" "$SECRET_NAME" "$NAMESPACE" <<'PYEOF'
import base64
import json
import os
import sys

configmap_path, candidate_path, secret_name, namespace = sys.argv[1:5]
with open(configmap_path) as stream:
    legacy_data = json.load(stream).get("data", {})

required_db_keys = ("db_url", "db_user", "db_pass")
missing_keys = [key for key in required_db_keys if not legacy_data.get(key)]
bootstrap_password = os.environ.get("WATCHTOWER_BOOTSTRAP_ADMIN_PASSWORD", "")
if missing_keys:
    print("ERROR: legacy ConfigMap is missing non-empty values for: "
          + ",".join(missing_keys), file=sys.stderr)
    sys.exit(1)
if not bootstrap_password:
    print("ERROR: WATCHTOWER_BOOTSTRAP_ADMIN_PASSWORD is required only when creating "
          "the missing Kubernetes Secret.", file=sys.stderr)
    sys.exit(1)

data = {key: base64.b64encode(legacy_data[key].encode()).decode()
        for key in required_db_keys}
data["bootstrap_admin_password"] = base64.b64encode(
    bootstrap_password.encode()).decode()
candidate = {
    "apiVersion": "v1",
    "kind": "Secret",
    "metadata": {"name": secret_name, "namespace": namespace},
    "type": "Opaque",
    "data": data,
}
with open(candidate_path, "w") as stream:
    json.dump(candidate, stream)
PYEOF
  chmod 600 "$CANDIDATE_SECRET_FILE"
  unset WATCHTOWER_BOOTSTRAP_ADMIN_PASSWORD || true
  echo "    Kubernetes Secret is missing; migrating legacy ConfigMap values (values not displayed)"
  if [[ "$DRY_RUN" == true ]]; then
    echo "    [dry-run] Would create Kubernetes Secret '$SECRET_NAME'"
  else
    kubectl create -f "$CANDIDATE_SECRET_FILE"
    echo "    Secret '$SECRET_NAME' created successfully"
  fi
  echo "    Legacy ConfigMap '$SECRET_NAME' retained for rollback; remove it after verifying the rollout"
fi

rm -rf "$SECRET_WORK_DIR"
trap - EXIT

# ---------------------------------------------------------------------------
# 4. ECR login
# ---------------------------------------------------------------------------
echo "==> Logging into ECR ($ECR_REGISTRY)..."
aws ecr get-login-password --region "$AWS_REGION" --profile "$AWS_PROFILE" \
  | docker login --username AWS --password-stdin "$ECR_REGISTRY"

# ---------------------------------------------------------------------------
# 5. Work out the next 26.1.N tag by asking ECR what the highest existing
#    one is (not a local counter file, so it can't drift out of sync with
#    what other people have already pushed).
# ---------------------------------------------------------------------------
echo "==> Determining next image tag..."
ESCAPED_PREFIX="${VERSION_PREFIX//./\\.}"
LAST_N=$(aws ecr describe-images \
    --repository-name "$IMAGE_REPO" \
    --region "$AWS_REGION" \
    --profile "$AWS_PROFILE" \
    --query "imageDetails[].imageTags[]" \
    --output text 2>/dev/null \
  | tr '\t' '\n' \
  | grep -E "^${ESCAPED_PREFIX}\.[0-9]+\$" \
  | sed -E "s/^${ESCAPED_PREFIX}\.//" \
  | sort -n \
  | tail -1) || true

if [[ -z "${LAST_N:-}" ]]; then
  NEXT_N=1
  echo "    No existing ${VERSION_PREFIX}.x tags found in $IMAGE_REPO — starting at ${VERSION_PREFIX}.1"
else
  NEXT_N=$((LAST_N + 1))
fi

TAG="${VERSION_PREFIX}.${NEXT_N}"
IMAGE_LOCAL="${IMAGE_REPO}:${TAG}"
IMAGE_REMOTE="${ECR_REGISTRY}/${IMAGE_REPO}:${TAG}"
echo "==> Next tag: $TAG"

# ---------------------------------------------------------------------------
# 6. Build / tag / push
# ---------------------------------------------------------------------------
# Skip the build if this exact tag is already sitting in the local image
# cache -- matters most after a failed docker push: since the tag above was
# computed as "highest existing ECR tag + 1", a retry after a push failure
# computes that same tag again, and the local image from the prior attempt
# is still good.
if docker image inspect "$IMAGE_LOCAL" >/dev/null 2>&1; then
  echo "==> $IMAGE_LOCAL already built locally, skipping build"
else
  echo "==> Building $IMAGE_LOCAL..."
  docker build . -t "$IMAGE_LOCAL" --platform linux/amd64
fi

echo "==> Tagging as $IMAGE_REMOTE..."
docker tag "$IMAGE_LOCAL" "$IMAGE_REMOTE"

echo "==> Pushing $IMAGE_REMOTE..."
run_if_not_dry docker push "$IMAGE_REMOTE"

# ---------------------------------------------------------------------------
# 7. Render deploy.yaml into a scratch copy (see the "7." bullet at the top
#    of this file for the full explanation of what gets overridden and why).
# ---------------------------------------------------------------------------
echo "==> Preparing deploy manifest..."
TMP_DIR=$(mktemp -d)
trap 'rm -rf "$TMP_DIR"' EXIT
RENDERED_DEPLOY_FILE="$TMP_DIR/deploy.yaml"
cp "$DEPLOY_FILE" "$RENDERED_DEPLOY_FILE"

# !!!IMAGE_LOCATION!!! and !!!APP_VERSION!!! are plain-text substituted before
# the YAML-aware rendering pass. They are quoted in deploy.yaml so the source
# manifest itself remains valid YAML.
#
# APP_VERSION is deliberately NOT in the python renderer's FEATURE_ENV_VARS
# inherit-from-live list below -- it must always be this deploy's own tag,
# never re-published from whatever was previously live (same reasoning as
# the ingress host: see the "NEVER inherited" comment further down).
sed -i.bak "s#!!!IMAGE_LOCATION!!!#${IMAGE_REMOTE}#" "$RENDERED_DEPLOY_FILE" && rm -f "${RENDERED_DEPLOY_FILE}.bak"
sed -i.bak "s#!!!APP_VERSION!!!#${TAG}#" "$RENDERED_DEPLOY_FILE" && rm -f "${RENDERED_DEPLOY_FILE}.bak"

# certificate-arn / security-groups are the two fields with no usable
# default in deploy.yaml (just placeholder text) — resolved here, before
# the YAML renderer runs, so a missing value stops the script immediately
# with a clear message instead of getting silently written into the
# manifest as literal placeholder text.
for entry in \
  "certificate-arn|<Cert ARN, get it from old deployment or AWS>|alb.ingress.kubernetes.io/certificate-arn" \
  "security-groups|<Get Security group from AWS ex: sg-XXXXXX>|alb.ingress.kubernetes.io/security-groups"; do
  IFS='|' read -r label placeholder annotation_key <<< "$entry"
  existing=$(kubectl get ingress watchtower-ingress -n "$NAMESPACE" \
    -o jsonpath="{.metadata.annotations.${annotation_key//./\\.}}" 2>/dev/null || true)
  if [[ -z "$existing" ]]; then
    echo "ERROR: no live value found for $label, and deploy.yaml only has placeholder text for it (no usable default)." >&2
    echo "       Fill it in manually in deploy.yaml, or apply once by hand first, then re-run." >&2
    exit 1
  fi
  echo "    Reusing $label from currently-deployed ingress: $existing"
  sed -i.bak "s#${placeholder}#${existing}#" "$RENDERED_DEPLOY_FILE" && rm -f "${RENDERED_DEPLOY_FILE}.bak"
done

# Everything else (replicas, resource sizing, feature-flag env vars,
# group.name, tags) has a real default already in deploy.yaml, so it's safe
# to hand off to a proper YAML-aware renderer: load, override in place where
# live data exists, leave the file's own default alone where it doesn't.
python3 -B - "$RENDERED_DEPLOY_FILE" "$RENDERED_DEPLOY_FILE" "$NAMESPACE" "$INGRESS_HOST" \
  "$DEPLOY_SCRIPT_DIR/scripts" "$AWS_SECURITY_CONFIG_FILE" "$ENVIRONMENT" "$DEPLOY_ACCOUNT_ID" "$AWS_REGION" <<'PYEOF'
import json
import subprocess
import sys

import yaml

DEPLOY_FILE, OUT_FILE, NAMESPACE, INGRESS_HOST = sys.argv[1:5]
sys.path.insert(0, sys.argv[5])
from aws_security_deploy_config import apply_settings, load_settings
AWS_SECURITY_CONFIG_FILE, ENVIRONMENT, ACCOUNT_ID, AWS_REGION = sys.argv[6:10]
security_settings = load_settings(AWS_SECURITY_CONFIG_FILE, ENVIRONMENT, ACCOUNT_ID, AWS_REGION)

RESOURCE_FIELDS = [("requests", "cpu"), ("requests", "memory"),
                    ("limits", "cpu"), ("limits", "memory")]
FEATURE_ENV_VARS = [
    "SPRING_PROFILES_ACTIVE",
    "watchtower.runAfterStartup",
    "watchtower.threads.prscan",
    "watchtower.threads.uploadscan",
    "watchtower.queue.sqs.submission-enabled",
    "watchtower.queue.sqs.visibility-extension-seconds",
    "WATCHTOWER_AWS_SECURITY_MAX_CONCURRENT_REVIEWS",
    "WATCHTOWER_CLOUDWATCH_ENABLED",
    "WATCHTOWER_CLOUDWATCH_NAMESPACE",
    "WATCHTOWER_CLOUDWATCH_REGION",
    "WATCHTOWER_CLOUDWATCH_STEP",
    "WATCHTOWER_METRICS_ZONE",
    "TZ",
]
# Must match the ServiceAccount object's metadata.name in deploy.yaml, and the
# system:serviceaccount:<namespace>:<name> subject already baked into the IRSA role's
# trust policy (see AWS_PROVISIONING.md / scripts/provision-aws.sh). If this ever
# needs to change, it has to change in all three places together.
REQUIRED_SERVICE_ACCOUNT = "watchtower-sa"
REQUIRED_SECRET_REFS = {
    "JDBC_URL": ("watchtower-secrets", "db_url"),
    "JDBC_USERNAME": ("watchtower-secrets", "db_user"),
    "JDBC_PASSWORD": ("watchtower-secrets", "db_pass"),
    "WATCHTOWER_BOOTSTRAP_ADMIN_PASSWORD": (
        "watchtower-secrets", "bootstrap_admin_password"
    ),
}


def kubectl_get_json(resource, name):
    result = subprocess.run(
        ["kubectl", "get", resource, name, "-n", NAMESPACE, "-o", "json"],
        capture_output=True, text=True,
    )
    return json.loads(result.stdout) if result.returncode == 0 else None


live_deployment = kubectl_get_json("deployment", "watchtower-deployment")
live_ingress = kubectl_get_json("ingress", "watchtower-ingress")
live_container = (
    live_deployment["spec"]["template"]["spec"]["containers"][0]
    if live_deployment else None
)


def live_env_value(name):
    if not live_container:
        return None
    for e in live_container.get("env", []):
        if e.get("name") == name:
            return e.get("value")
    return None


def live_annotation(key):
    if not live_ingress:
        return None
    return live_ingress.get("metadata", {}).get("annotations", {}).get(key)


with open(DEPLOY_FILE) as f:
    docs = list(yaml.safe_load_all(f))

for doc in docs:
    kind = doc.get("kind")

    if kind == "Deployment":
        pod_spec = doc["spec"]["template"]["spec"]
        container = pod_spec["containers"][0]

        # Fail closed rather than silently deploying a pod with no AWS credentials.
        # deploy.yaml is the source of truth for this field - this script never sets
        # or overwrites it - so a mismatch here means deploy.yaml itself regressed.
        actual_sa = pod_spec.get("serviceAccountName")
        if actual_sa != REQUIRED_SERVICE_ACCOUNT:
            print(f"ERROR: deploy.yaml's Deployment has serviceAccountName="
                  f"{actual_sa!r}, expected {REQUIRED_SERVICE_ACCOUNT!r}.")
            print("       Without this, the pod runs as the 'default' ServiceAccount "
                  "and every AWS SDK call (S3/SQS) fails with a credentials error.")
            print("       Fix deploy.yaml's Deployment.spec.template.spec."
                  "serviceAccountName and re-run.")
            sys.exit(1)
        print(f"    Verified serviceAccountName: {actual_sa}")

        pod_security = pod_spec.get("securityContext", {})
        container_security = container.get("securityContext", {})
        dropped_capabilities = container_security.get("capabilities", {}).get("drop", [])
        if (pod_security.get("runAsNonRoot") is not True
                or pod_security.get("runAsUser") in (None, 0)
                or container_security.get("allowPrivilegeEscalation") is not False
                or "ALL" not in dropped_capabilities):
            print("ERROR: deploy.yaml is missing the required non-root container security settings.")
            sys.exit(1)
        print("    Verified non-root pod/container security settings")

        missing_probes = [
            probe for probe in ("startupProbe", "readinessProbe", "livenessProbe")
            if probe not in container
        ]
        if missing_probes:
            print(f"ERROR: deploy.yaml is missing required probes: {', '.join(missing_probes)}")
            sys.exit(1)

        env_by_name = {item.get("name"): item for item in container.get("env", [])}
        for env_name, (secret_name, secret_key) in REQUIRED_SECRET_REFS.items():
            reference = (env_by_name.get(env_name, {}).get("valueFrom", {})
                         .get("secretKeyRef", {}))
            if reference.get("name") != secret_name or reference.get("key") != secret_key:
                print(f"ERROR: deploy.yaml env {env_name} must reference "
                      f"Secret {secret_name!r} key {secret_key!r}.")
                sys.exit(1)
        print("    Verified database/bootstrap Secret references")

        if live_deployment is None:
            print("    No live deployment found on this cluster yet "
                  "-- using deploy.yaml's defaults for replicas/resources/env vars")
        else:
            live_replicas = live_deployment["spec"]["replicas"]
            print(f"    Reusing replicas from live deployment: {live_replicas}")
            doc["spec"]["replicas"] = live_replicas

            for bucket, key in RESOURCE_FIELDS:
                live_val = live_container.get("resources", {}).get(bucket, {}).get(key)
                if live_val is not None:
                    print(f"    Reusing resources.{bucket}.{key} from live deployment: {live_val}")
                    container["resources"][bucket][key] = live_val

        for e in container["env"]:
            if e.get("name") in FEATURE_ENV_VARS:
                live_val = live_env_value(e["name"])
                if live_val is not None:
                    print(f"    Reusing {e['name']} from live deployment: {live_val}")
                    e["value"] = live_val
            elif e.get("name") == "watchtower.publicUrl":
                # Same reasoning as the Ingress host below: always derived from
                # INGRESS_HOST for this deploy, never inherited from a live deployment
                # that may have been provisioned for a different environment.
                public_url = f"https://{INGRESS_HOST}"
                print(f"    Setting watchtower.publicUrl: {public_url}")
                e["value"] = public_url

        # Dev-only test switches. Added to the container only when deploying dev, so prod
        # never inherits them: reviewed rule-test fixtures baked into the image, and live
        # Betterleaks verification (which sends a found key to its provider).
        if ENVIRONMENT == "dev":
            dev_only_env = {
                "WATCHTOWER_RULE_TESTING_FIXTURE_DIRECTORY": "/opt/watchtower/rule-fixtures",
                "WATCHTOWER_BETTERLEAKS_VERIFICATION_ENABLED": "true",
            }
            for name, value in dev_only_env.items():
                container["env"] = [x for x in container["env"] if x.get("name") != name]
                container["env"].append({"name": name, "value": value})
                print(f"    Setting {name} (dev only): {value}")

    elif kind == "Ingress":
        # certificate-arn / security-groups are already resolved by the
        # bash step above this script; only override the two fields here
        # that have a real default in deploy.yaml to fall back to.
        ann = doc["metadata"]["annotations"]
        for key in ("group.name", "tags"):
            live_val = live_annotation(f"alb.ingress.kubernetes.io/{key}")
            if live_val is not None:
                print(f"    Reusing {key} from live ingress: {live_val}")
                ann[f"alb.ingress.kubernetes.io/{key}"] = live_val

        # Host is set from INGRESS_HOST (per-environment, see deploy.sh) and
        # NEVER inherited from whatever is live -- a prior dev deploy publishing
        # the prod hostname (watchtower.example.net) here is what broke prod
        # traffic, so this always wins regardless of what's currently deployed.
        print(f"    Setting ingress host: {INGRESS_HOST}")
        doc["spec"]["tls"][0]["hosts"] = [INGRESS_HOST]
        for rule in doc["spec"]["rules"]:
            rule["host"] = INGRESS_HOST

apply_settings(docs, security_settings, ACCOUNT_ID, AWS_REGION, ENVIRONMENT)

with open(OUT_FILE, "w") as f:
    yaml.safe_dump_all(docs, f, default_flow_style=False, sort_keys=False)
PYEOF

# ---------------------------------------------------------------------------
# 8. Apply
# ---------------------------------------------------------------------------
echo "==> Applying manifest to $EKS_CLUSTER ($NAMESPACE namespace)..."
if [[ "$DRY_RUN" == true ]]; then
  echo "    [dry-run] kubectl apply -f $RENDERED_DEPLOY_FILE"
  echo "    Rendered manifest kept at: $RENDERED_DEPLOY_FILE (dry-run skips cleanup)"
  trap - EXIT
else
  kubectl apply -f "$RENDERED_DEPLOY_FILE"
fi

echo "==> Done. Deployed $IMAGE_REMOTE to $ENVIRONMENT ($EKS_CLUSTER)."
